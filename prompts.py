def honest(kind: str, reason: str, tone: str | None = None, gender: str | None = None) -> str:
    """kind: fail (инструмент вызван и ответил ошибкой), none (инструмент не вызывался), partial (часть вышла)."""
    tone = tone or C.tone()
    forms = GENDER_FORMS[gender if gender in GENDER_FORMS else C.gender()]
    return HONEST.get(tone, HONEST["derzkiy"])[kind].format(reason=reason, didnt=forms["didnt"])
