"""Озвучка. Яндекс пикает мат в tts по словарю. Маркер ударения «+» перед гласной он не
произносит, но токен со вставленным «+» фильтр не опознаёт — слово звучит, пик не срабатывает.
Порядок важен: специфичное раньше общего. Только поле tts, текст в приложении остаётся полным."""
import re

SWEAR_TTS = [
    (r"пиздец", "пизд+ец"), (r"пизд(?!\+)", "п+изд"),
    (r"хуясе", "ху+ясе"), (r"хуёво", "ху+ёво"), (r"хуев", "ху+ев"),
    (r"нахуй", "нах+уй"), (r"нихуя", "них+уя"), (r"охуе", "ох+уе"),
    (r"хуйн", "х+уйн"), (r"хуй", "х+уй"),
    (r"блядь", "бл+ядь"), (r"блять", "бл+ять"), (r"бля", "бл+я"),
    (r"ёбну", "+ёбну"), (r"ебать", "+ебать"), (r"ебал", "+ебал"), (r"ебан", "+ебан"),
    (r"сука", "с+ука"),
]


def deswear(text: str) -> str:
    for pat, repl in SWEAR_TTS:
        text = re.sub(pat, repl, text, flags=re.IGNORECASE)
    return text


def clean(text: str) -> str:
    text = re.sub(r"[`*_#>\[\]{}|\\]", "", text)
    text = re.sub(r"https?://\S+", "ссылка", text)
    return deswear(text)[:1000]
